// Function: validatePoints()
// Returns true if the 4 points are not collinear/coplanar.
bool validatePoints(cluster_PC pts[SAMPLE_SIZE]) {
    // Compute vectors v1, v2, v3 from the first point.
    int16_t v1x = pts[1].x - pts[0].x;
    int16_t v1y = pts[1].y - pts[0].y;
    int16_t v1z = pts[1].z - pts[0].z;

    int16_t v2x = pts[2].x - pts[0].x;
    int16_t v2y = pts[2].y - pts[0].y;
    int16_t v2z = pts[2].z - pts[0].z;

    int16_t v3x = pts[3].x - pts[0].x;
    int16_t v3y = pts[3].y - pts[0].y;
    int16_t v3z = pts[3].z - pts[0].z;

    // Calculate the normal vector from v1 x v2.
    int16_t nx = v1y * v2z - v1z * v2y;
    int16_t ny = v1z * v2x - v1x * v2z;
    int16_t nz = v1x * v2y - v1y * v2x;
    float norm = sqrtf((float)(nx * nx + ny * ny + nz * nz));
    if (norm < EPS)
        return false;  // Points are collinear

    // Check if fourth point lies in the same plane (if dot product is near zero)
    int32_t dot = nx * v3x + ny * v3y + nz * v3z;
    // Normalize the dot product by the normal vector length.
    //TODO: custom fabs implementation
    if (car_abs(dot) < EPS)
        return false; // Coplanar

    return true;
}

float evalSphere(SphereModel *model,  cluster_PC *p) {
    float dx = p->x - model->a;
    float dy = p->y - model->b;
    float dz = p->z - model->c;
    float dist = sqrtf(dx * dx + dy * dy + dz * dz);
    return car_fabs(dist - model->d);
}

bool fitSphere(cluster_PC pts[SAMPLE_SIZE], SphereModel *model) {
    // Construct matrix A: each row is [x y z 1].
    int64_t A[4][4] = {
        { pts[0].x, pts[0].y, pts[0].z, 1 },
        { pts[1].x, pts[1].y, pts[1].z, 1 },
        { pts[2].x, pts[2].y, pts[2].z, 1 },
        { pts[3].x, pts[3].y, pts[3].z, 1 }
    };

    // Construct vector B: - (x^2 + y^2 + z^2) for each point.
    int64_t B[4] = {
        -(pts[0].x*pts[0].x + pts[0].y*pts[0].y + pts[0].z*pts[0].z),
        -(pts[1].x*pts[1].x + pts[1].y*pts[1].y + pts[1].z*pts[1].z),
        -(pts[2].x*pts[2].x + pts[2].y*pts[2].y + pts[2].z*pts[2].z),
        -(pts[3].x*pts[3].x + pts[3].y*pts[3].y + pts[3].z*pts[3].z)
    };
    // Compute determinant D of A.
    int64_t D = det4(A);
    if (D <= EPS) {
        return false; // Degenerate (matrix is nearly singular)
    }

    // Build matrices for D1, D2, D3, D4.
    int64_t M1[4][4] = {
        { B[0], A[0][1], A[0][2], A[0][3] },
        { B[1], A[1][1], A[1][2], A[1][3] },
        { B[2], A[2][1], A[2][2], A[2][3] },
        { B[3], A[3][1], A[3][2], A[3][3] }
    };
    int64_t M2[4][4] = {
        { A[0][0], B[0], A[0][2], A[0][3] },
        { A[1][0], B[1], A[1][2], A[1][3] },
        { A[2][0], B[2], A[2][2], A[2][3] },
        { A[3][0], B[3], A[3][2], A[3][3] }
    };
    int64_t M3[4][4] = {
        { A[0][0], A[0][1], B[0], A[0][3] },
        { A[1][0], A[1][1], B[1], A[1][3] },
        { A[2][0], A[2][1], B[2], A[2][3] },
        { A[3][0], A[3][1], B[3], A[3][3] }
    };
    int64_t M4[4][4] = {
        { A[0][0], A[0][1], A[0][2], B[0] },
        { A[1][0], A[1][1], A[1][2], B[1] },
        { A[2][0], A[2][1], A[2][2], B[2] },
        { A[3][0], A[3][1], A[3][2], B[3] }
    };

    int64_t D1 = det4(M1);
    int64_t D2 = det4(M2);
    int64_t D3 = det4(M3);
    int64_t D4 = det4(M4);

    double centerX = -0.5f * D1/ D;
    double centerY = -0.5f * D2 / D;
    double centerZ = -0.5f * D3  / D;
    double radiusSquared = centerX * centerX + centerY * centerY + centerZ * centerZ - D4 / D;
    if (radiusSquared < 0.0f)
        return false; // Invalid sphere (negative radius squared)

    model->a = centerX;
    model->b = centerY;
    model->c = centerZ;
    model->d = sqrtf(radiusSquared);

     return true;
}
