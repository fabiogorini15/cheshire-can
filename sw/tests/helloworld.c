int64_t det4(int64_t m[4][4]) {
    int64_t d = m[0][0] * det3(m[1][1], m[1][2], m[1][3],
                      m[2][1], m[2][2], m[2][3],
                      m[3][1], m[3][2], m[3][3])
     - m[0][1] * det3(m[1][0], m[1][2], m[1][3],
                      m[2][0], m[2][2], m[2][3],
                      m[3][0], m[3][2], m[3][3])
     + m[0][2] * det3(m[1][0], m[1][1], m[1][3],
                      m[2][0], m[2][1], m[2][3],
                      m[3][0], m[3][1], m[3][3])
     - m[0][3] * det3(m[1][0], m[1][1], m[1][2],
                      m[2][0], m[2][1], m[2][2],
                      m[3][0], m[3][1], m[3][2]);
    return d;
}

void ransacSphereFitting(cluster_PC points[], SphereModel *bestModel, int16_t cluster_dim) {

    uint16_t bestInlierCount = 0;
    int16_t bestError = -1;
    SphereModel model;

     
    if (cluster_dim < SAMPLE_SIZE) {
        // Not enough points to fit a sphere.
        bestModel->numBestInliers = 0;
        bestModel->iterationsPerformed = 0;
        return;
    }
    
    // Initialize iteration count.
    bestModel->iterationsPerformed = 0;
    
    // RANSAC parameters. 
    float w = INITIAL_ESITIMATE_INLIER_RATIO;
    int16_t maxRequiredIterations = MAX_ITERATIONS;
    /* TODO: replace with pre-calculated log(1-p) and LKT + test*/
        maxRequiredIterations = (int)(LOG_1_P/log(1.0 - pow(w, 4)));
        if (maxRequiredIterations > MAX_ITERATIONS)
            maxRequiredIterations = MAX_ITERATIONS;
    
    
    for (int16_t iteration = 0; iteration < maxRequiredIterations; iteration++) {
        bestModel->iterationsPerformed++;
        // Randomly select 4 unique points.
        uint16_t sampleIndices[SAMPLE_SIZE];
        bool validSelection = false;
        cluster_PC samplePoints[SAMPLE_SIZE];
        while (!validSelection) {
            // Simple unique random selection.
            bool used[MAX_POINTS] = { false };
            for (uint16_t i = 0; i < SAMPLE_SIZE; i++) {
                uint16_t idx;
                do {
                    idx = rand() % cluster_dim;
                } while (used[idx]);
                used[idx] = true;
                sampleIndices[i] = idx;
                samplePoints[i] = points[idx];
            }
            validSelection = validatePoints(samplePoints);
        }
        
        // Fit sphere to the sample points.
        if (!fitSphere(samplePoints, &model))
            continue; // Invalid model

        // Evaluate the model against all points.
        uint16_t InliersIndex[MAX_POINTS];
        uint16_t inlierCount = 0;
        float errorSum = 0.0f;
        for (int i = 0; i < cluster_dim; i++) {
            float dist = evalSphere(&model, &points[i]);
            if (dist < 50.0f) { // Check if point is an inlier
                InliersIndex[inlierCount] = i;
                inlierCount++;
                errorSum += dist;
            }
        }
        
        float meanError = (inlierCount > 0) ? errorSum / inlierCount : -1;
        
        // Update the best model if the current one is better.
        if ((inlierCount > bestInlierCount) ||
            (inlierCount == bestInlierCount && meanError < bestError)) {
            *bestModel = model;
            bestModel->numBestInliers = inlierCount;
            bestError = meanError;
            bestInlierCount = inlierCount;
            // Save best inlier indices and corresponding points.
             for (int i = 0; i < inlierCount; i++) {
                bestModel->bestInliersIndex[i] = InliersIndex[i]; // these are indices of cluster points
                bestModel->bestInlierPoints[i] = points[InliersIndex[i]];
            }
            
            // Update estimated inlier ratio and recalc required iterations.
            w = ((float)bestInlierCount) / cluster_dim;
            
             /* TODO: replace with pre-calculated log(1-p) and LKT + test*/
             uint16_t newMaxIterations = (int)(LOG_1_P/log(1.0f - pow(w, 4)));
                if (maxRequiredIterations > MAX_ITERATIONS)
                         maxRequiredIterations = MAX_ITERATIONS;
                     if (newMaxIterations < maxRequiredIterations)
                        maxRequiredIterations = newMaxIterations;
        }
        
        // Early termination if iterations reached.
        if (iteration >= maxRequiredIterations - 1)
            break;
    }
}


int64_t det3(int64_t a1, int64_t a2, int64_t a3,
    int64_t b1, int64_t b2, int64_t b3,
    int64_t c1, int64_t c2, int64_t c3) {
    return a1 * (b2 * c3 - b3 * c2)
    - a2 * (b1 * c3 - b3 * c1)
    + a3 * (b1 * c2 - b2 * c1);
}

